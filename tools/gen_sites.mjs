// Generates probe/sites.h from the upstream hook list (DEVELOP.md 3.2, M0).
// Sources: upstream module/build.py HOOKS (comments stripped, so the commented-out stats_hunted
// at build.py:62 is not a site), module/gear_hooks.txt (build.py:119) and the 3 item replace
// hooks of build.py:193-195. Expected words come from the MHGU 1.4.0 main flat image
// (flat offset = main offset + 0x100), so the probe can prove its base is right.
//
// usage: node tools/gen_sites.mjs <upstream checkout> <main.140.flat.bin> <out sites.h>
// SPDX-License-Identifier: GPL-3.0-or-later
import fs from "node:fs";
import path from "node:path";

const [up, flat, out] = process.argv.slice(2);
if (!out) {
  console.error("usage: node tools/gen_sites.mjs <upstream checkout> <main.140.flat.bin> <out sites.h>");
  process.exit(2);
}

const build = fs.readFileSync(path.join(up, "module/build.py"), "utf8");
const block = build.match(/^HOOKS = \[([\s\S]*?)^\]/m);
if (!block) throw new Error("build.py: HOOKS = [ ... ] not found");
const tuples = (text) => [...text.split("\n").map((l) => l.split("#")[0]).join("\n")
  .matchAll(/\('(\w+)',\s*(0x[0-9A-Fa-f]+)\)/g)].map((m) => ({ name: m[1], off: parseInt(m[2], 16) }));
const core = tuples(block[1]).map((s) => ({ ...s, group: "core" }));
const gear = fs.readFileSync(path.join(up, "module/gear_hooks.txt"), "utf8").split("\n")
  .filter((l) => l.trim()).map((l) => { const [n, a] = l.trim().split(/\s+/); return { name: n, off: parseInt(a, 16), group: "gear" }; });
// build.py:193-195: `if ITEMS_APPENDED: HOOKS += [...]`. The port appends MH4U items, so these are
// always registered; they are replace hooks (REPLACE_HOOKS |= {...}).
const itemAdd = build.match(/^if ITEMS_APPENDED:\r?\n\s+HOOKS \+= \[([^\]]*)\]\r?\n\s+REPLACE_HOOKS \|= \{([^}]*)\}/m);
if (!itemAdd) throw new Error("build.py: `if ITEMS_APPENDED: HOOKS += [...]` block not found");
const item = tuples(itemAdd[1]).map((s) => ({ ...s, group: "item" }));
const replace = new Set([...(build.match(/^REPLACE_HOOKS = \{([^}]*)\}/m)?.[1] ?? "").matchAll(/'(\w+)'/g),
  ...itemAdd[2].matchAll(/'(\w+)'/g)].map((m) => m[1]));
// guard against other HOOKS growth this script does not model (gear at :119, items at :194)
const growth = [...build.matchAll(/^\s*HOOKS\s*(\+=|=\s*HOOKS|\.append|\.extend)/gm)].length;
if (growth !== 2) throw new Error(`build.py: expected 2 HOOKS additions (gear, items), found ${growth}`);

const sites = [...core, ...gear, ...item];
const seen = new Map();
for (const s of sites) {
  if (seen.has(s.off)) throw new Error(`duplicate site ${s.off.toString(16)}: ${seen.get(s.off)} and ${s.name}`);
  seen.set(s.off, s.name);
  // DEVELOP.md 3.6: Forge's own hook addresses must not appear (0x3DA8FC is shared on purpose)
  if ([0x887810, 0x88784c, 0xb8692c].includes(s.off)) throw new Error(`${s.name} collides with a Forge hook`);
}

const img = fs.readFileSync(flat);
for (const s of sites) s.word = img.readUInt32LE(s.off + 0x100);

const head = `/* Generated by tools/gen_sites.mjs - do not edit.
 * upstream: ${sites.length} sites (${core.length} build.py HOOKS + ${gear.length} gear_hooks.txt + ${item.length} item); replace hooks: ${[...replace].join(", ") || "none"}
 * expected words: MHGU 1.4.0 main flat image, offset + 0x100.
 * SPDX-License-Identifier: GPL-3.0-or-later */
#ifndef MH4U_SITES_H
#define MH4U_SITES_H
#include <stdint.h>

typedef struct {
    const char* name;
    uint32_t off;     /* main-relative */
    uint32_t word;    /* original 1.4.0 instruction word */
    uint8_t gear;     /* 1 = gear_hooks.txt */
    uint8_t replace;  /* 1 = REPLACE_HOOKS (function replaced, not resumed) */
} Mh4uSite;

#define MH4U_SITE_COUNT ${sites.length}u
static const Mh4uSite kMh4uSites[MH4U_SITE_COUNT] = {
`;
const rows = sites.map((s) =>
  `    {"${s.name}", 0x${s.off.toString(16).toUpperCase()}u, 0x${s.word.toString(16).toUpperCase().padStart(8, "0")}u, ${s.group === "gear" ? 1 : 0}, ${replace.has(s.name) ? 1 : 0}},`);
fs.writeFileSync(out, head + rows.join("\n") + "\n};\n\n#endif\n");
console.log(`${out}: ${sites.length} sites (${core.length} core + ${gear.length} gear + ${item.length} item), replace ${replace.size}`);
